// Builds the packaged templates (templates/<id>/{manifest.json,template.html,template.css}) into:
//   - templates/templates.generated.js : manifest + markup parts, loaded by packaged-templates.js
//   - the <style id="packaged-templates-css"> block in index.html (the editor preview is drawn in a
//     shadow root that copies only inline styles, same reason as scene-templates.css)
// Run `npm run build:templates` after editing a template. tests/unit/packaged-templates.test.mjs
// fails if either output is stale. Designer CSS is written as ordinary page CSS; every rule is
// scoped here under the template's root class so it can never leak into the editor.
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const START = '<style id="packaged-templates-css">';
export const END = '</style><!--/packaged-templates-css-->';

// Splits a stylesheet into top level blocks, honouring nested braces and strings.
function blocks(css) {
  const out = []; let depth = 0, start = 0, quote = '';
  for (let i = 0; i < css.length; i++) {
    const c = css[i];
    if (quote) { if (c === quote && css[i - 1] !== '\\') quote = ''; continue; }
    if (c === '"' || c === "'") { quote = c; continue; }
    if (c === '{') depth++;
    else if (c === '}') { depth--; if (depth === 0) { out.push(css.slice(start, i + 1).trim()); start = i + 1; } }
    else if (c === ';' && depth === 0) { out.push(css.slice(start, i + 1).trim()); start = i + 1; }
  }
  return out.filter(Boolean);
}
function splitSelectors(sel) {
  const parts = []; let depth = 0, cur = '';
  for (const c of sel) {
    if (c === '(' ) depth++; if (c === ')') depth--;
    if (c === ',' && depth === 0) { parts.push(cur); cur = ''; } else cur += c;
  }
  parts.push(cur);
  return parts.map(s => s.trim()).filter(Boolean);
}
export function scopeCss(css, scope, prefix = '') {
  css = css.replace(/\/\*[\s\S]*?\*\//g, '');
  return blocks(css).map(block => {
    const open = block.indexOf('{');
    if (open < 0) return block;
    const head = block.slice(0, open).trim(), body = block.slice(open + 1, block.lastIndexOf('}'));
    if (head.startsWith('@font-face') || head.startsWith('@keyframes')) return block;
    if (head.startsWith('@')) return `${head}{${scopeCss(body, scope, prefix)}}`;
    const selectors = splitSelectors(head).map(s => {
      if (/^(:root|html|body)$/.test(s)) return `.${scope}`;
      return `.${scope} ${s.replace(/^(html|body)\s+/, '').replace(/\.([a-zA-Z_][\w-]*)/g, `.${prefix}$1`)}`;
    });
    return `${selectors.join(',')}{${body.trim().replace(/\s*\n\s*/g, '')}}`;
  }).join('\n');
}
// Class names in a designer's markup are prefixed too, so generic names (.button, .eyebrow) can never
// pick up the editor's own styles inside the preview.
export function prefixClasses(html, prefix) {
  return html.replace(/\sclass="([^"]*)"/g, (_, names) => ` class="${names.split(/\s+/).filter(Boolean).map(n => (n.includes('{{') ? n : prefix + n)).join(' ')}"`);
}
export function splitParts(html) {
  const parts = {};
  const re = /<!--part:(\w+)-->/g; let m, last = null, lastIndex = 0;
  while ((m = re.exec(html))) {
    if (last) parts[last] = html.slice(lastIndex, m.index).trim();
    last = m[1]; lastIndex = re.lastIndex;
  }
  if (last) parts[last] = html.slice(lastIndex).trim();
  return parts;
}

export function loadTemplates() {
  const dir = join(root, 'templates');
  return readdirSync(dir, { withFileTypes: true }).filter(d => d.isDirectory() && existsSync(join(dir, d.name, 'manifest.json'))).map(d => {
    const base = join(dir, d.name);
    const manifest = JSON.parse(readFileSync(join(base, 'manifest.json'), 'utf8'));
    const parts = splitParts(readFileSync(join(base, 'template.html'), 'utf8'));
    const css = scopeCss(readFileSync(join(base, 'template.css'), 'utf8'), manifest.root, manifest.prefix);
    for (const name of Object.keys(parts)) parts[name] = prefixClasses(parts[name], manifest.prefix);
    return { manifest, parts, css };
  });
}
export function generatedJs(list = loadTemplates()) {
  const data = {};
  for (const t of list) data[t.manifest.id] = { manifest: t.manifest, parts: t.parts };
  return `// GENERATED by scripts/build-templates.mjs. Do not edit by hand.\n(globalThis.PACKAGED_TEMPLATES = globalThis.PACKAGED_TEMPLATES || {}, Object.assign(globalThis.PACKAGED_TEMPLATES, ${JSON.stringify(data)}));\n`;
}
export function inlineBlock(list = loadTemplates()) {
  return `${START}\n${list.map(t => t.css).join('\n')}\n${END}`;
}
export function currentBlock(html) {
  const a = html.indexOf(START), b = html.indexOf(END);
  return a < 0 || b < 0 ? null : html.slice(a, b + END.length);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const list = loadTemplates();
  writeFileSync(join(root, 'templates/templates.generated.js'), generatedJs(list));
  const path = join(root, 'index.html');
  const html = readFileSync(path, 'utf8');
  const existing = currentBlock(html);
  if (!existing) throw new Error('packaged-templates-css block not found in index.html');
  writeFileSync(path, html.replace(existing, () => inlineBlock(list)));
  console.log(`packaged templates built: ${list.map(t => t.manifest.id).join(', ')}`);
}
