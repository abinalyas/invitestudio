// Regenerates functions/_shared/templates.js from the frontend template catalogue.
// Run `npm run gen:templates` after changing the catalogue. tests/unit/defects.test.mjs
// fails if the committed registry is out of date.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { LAUNCH_CATEGORY, launchTemplateIds } from './template-catalogue.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ids = launchTemplateIds();
const body = ids.map(id => `  '${id}',`).join('\n');
const source = `// GENERATED by scripts/generate-template-registry.mjs. Do not edit by hand.
//
// Explicit template registration (server side). A design can be created, changed to, or
// published only if it is listed here. The list is the frontend catalogue's designs in the
// "${LAUNCH_CATEGORY}" category (the launch scope), in catalogue order.
//
// Database rows that are not listed here are never offered, so a design that is not
// registered can never be drawn with a fallback.
export const LAUNCH_TEMPLATE_IDS = Object.freeze([
${body}
]);

export function isLaunchTemplate(id) {
  return LAUNCH_TEMPLATE_IDS.includes(id);
}
`;
writeFileSync(join(root, 'functions/_shared/templates.js'), source);
console.log(`template registry written: ${ids.length} ${LAUNCH_CATEGORY} designs`);
